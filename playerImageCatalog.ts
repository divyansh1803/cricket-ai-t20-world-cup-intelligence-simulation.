/**
 * Safely encodes asset URLs containing spaces or parentheses without ever double-encoding (%2520).
 */
export function toSafeAssetUrl(url?: string | null): string {
  if (!url) return "";
  try {
    return encodeURI(decodeURI(url));
  } catch {
    return encodeURI(url);
  }
}

/**
 * Maps a player name and/or player ID to their verified portrait asset in /players/.
 * Prioritizes exact player name match, normalized name match, and player ID match.
 */
export function getPlayerPhotoUrl(playerId?: string, name?: string): string | null {
  if (name) {
    const lowerName = name.toLowerCase().trim();
    if (PLAYER_PHOTO_CATALOG[lowerName]) return PLAYER_PHOTO_CATALOG[lowerName];
    const cleanName = lowerName.replace(/[^a-z0-9 ]/g, "").replace(/\s+/g, " ").trim();
    if (PLAYER_PHOTO_CATALOG[cleanName]) return PLAYER_PHOTO_CATALOG[cleanName];
    const compactName = lowerName.replace(/[^a-z0-9]/g, "");
    if (PLAYER_PHOTO_CATALOG[compactName]) return PLAYER_PHOTO_CATALOG[compactName];
  }
  if (playerId) {
    const lowerId = playerId.toLowerCase().trim();
    if (PLAYER_PHOTO_CATALOG[lowerId]) return PLAYER_PHOTO_CATALOG[lowerId];
  }
  return null;
}

/**
 * Resolves the best available portrait URL for a player object or name,
 * preferring real raster photographs mapped by name over generic SVG silhouettes.
 */
export function resolvePlayerImageUrl(player: { id?: string; name?: string; imageUrl?: string } | null | undefined): string {
  if (!player) return "/players/virat_kohli.jpg";
  const catalogByName = getPlayerPhotoUrl(player.id, player.name);
  if (catalogByName && !catalogByName.endsWith(".svg")) {
    return catalogByName;
  }
  if (player.imageUrl && !player.imageUrl.endsWith(".svg") && !player.imageUrl.includes("images.icc-cricket.com")) {
    return player.imageUrl.startsWith("/") || player.imageUrl.startsWith("http")
      ? player.imageUrl
      : `/players/${player.imageUrl}`;
  }
  if (catalogByName) {
    return catalogByName;
  }
  if (player.imageUrl && !player.imageUrl.includes("images.icc-cricket.com")) {
    return player.imageUrl.startsWith("/") || player.imageUrl.startsWith("http")
      ? player.imageUrl
      : `/players/${player.imageUrl}`;
  }
  return player.id ? `/players/${player.id.toLowerCase()}.svg` : "/players/virat_kohli.jpg";
}
