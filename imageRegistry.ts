/**
 * Validates player identity before rendering to prevent showing incorrect photos
 */
export function validatePlayerIdentity(playerIdOrStable: string, expectedCountry?: string): VerifiedImageRecord | null {
  const match = Object.values(VERIFIED_IMAGE_REGISTRY).find(
    (r) => r.id === playerIdOrStable || r.stableId === playerIdOrStable
  );
  if (!match) return null;
  if (expectedCountry && match.countryCode !== expectedCountry && match.teamId !== expectedCountry.toLowerCase()) {
    return null;
  }
  return match;
}
